# الگوهای با رجکس
REGEX_PATTERNS = [
    (r"встроенный выход #(\d+) снова в работе — проверка прошла", r"خروجی داخلی شماره \1 مجدداً فعال شد — تست با موفقیت انجام شد ✓"),
    (r"встроенный выход #(\d+) не отвечает: недоступен:", r"خروجی داخلی شماره \1 پاسخ نمی‌دهد: در دسترس نیست:"),
    (r"встроенный выход #(\d+) сменил выход на (.+) — снова используем", r"خروجی داخلی شماره \1 تغییر یافت به \2 — در حال استفاده مجدد"),
    (r"встроенный выход #(\d+)", r"خروجی داخلی شماره \1"),
    (r"маршрут гейт-хостов: (.+), было (.+)", r"تغییر مسیر دروازه: \1 (مسیر قبلی: \2)"),
    (r"(\d{2}:\d{2}:\d{2})\s+proxy\s+", r"\1 [پروکسی]   "),
    (r"(\d{2}:\d{2}:\d{2})\s+dns\s+", r"\1 [دی‌ان‌اس]   "),
    (r"(\d{2}:\d{2}:\d{2})\s+watchdog\s+", r"\1 [نگهبان]   "),
    (r"(\d{2}:\d{2}:\d{2})\s+gate\s+", r"\1 [دروازه]   "),
]


def translate_log_line(line: str) -> str:
    """ترجمه و تبدیل یک خط لاگ به فارسی"""
    if not line:
        return line

    result = line

    # جایگزینی با رجکس
    for pat, repl in REGEX_PATTERNS:
        result = re.sub(pat, repl, result)

    # جایگزینی عبارات کلیدی
    for ru, fa in PHRASE_TRANSLATIONS.items():
        if ru in result:
            result = result.replace(ru, fa)

    return result


def translate_log_text(text: str) -> str:
    """ترجمه کل متن لاگ‌ها خط به خط"""
    if not text:
        return ""
    lines = text.splitlines()
    translated_lines = [translate_log_line(l) for l in lines]
    return "\n".join(translated_lines)


def translate_gate_dict(data: dict) -> dict:
    """ترجمه مقادیر وضعیت دروازه gate.json به فارسی"""
    if not isinstance(data, dict):
        return data

    res = {}
    label_map = {
        "свой прокси": "پروکسی اختصاصی",
        "быстрый": "سریع",
        "прямой выход": "خروجی مستقیم",
        "резервный выход": "خروجی رزرو",
        "встроенный выход": "خروجی داخلی",
        "прямо без VPN": "مستقیم بدون VPN"
    }

    for k, v in data.items():
        if isinstance(v, str):
            trans_v = v
            for ru, fa in label_map.items():
                if ru in trans_v:
                    trans_v = trans_v.replace(ru, fa)
            trans_v = translate_log_line(trans_v)
            res[k] = trans_v
        elif isinstance(v, dict):
            res[k] = translate_gate_dict(v)
        elif isinstance(v, list):
            res[k] = [translate_gate_dict(item) if isinstance(item, dict) else item for item in v]
        else:
            res[k] = v

    return res
